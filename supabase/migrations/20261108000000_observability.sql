revoke all on public.ai_generation_examples from anon, authenticated;
grant select,insert,update,delete on public.ai_generation_examples to authenticated;
create policy "Superadmins manage ai_generation_examples" on public.ai_generation_examples for all to authenticated using ((select public.is_superadmin())) with check ((select public.is_superadmin()));
