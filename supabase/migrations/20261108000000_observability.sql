begin;
create table public.llm_providers (
 id bigint generated by default as identity primary key,
 name text not null unique check(length(name) between 1 and 120),
 adapter text not null default 'gemini' check(adapter in ('gemini','openai')),
 created_at timestamptz not null default now()
);
create table public.llm_models (
 id bigint generated by default as identity primary key,
 provider_id bigint not null references public.llm_providers(id) on delete restrict,
 name text not null check(length(name) between 1 and 120),
 model_id text not null check(model_id ~ '^[a-zA-Z0-9._-]+$'),
 enabled boolean not null default true,
 created_at timestamptz not null default now(), unique(provider_id,model_id)
);
create table public.prompt_chains (
 id bigint generated by default as identity primary key,
 name text not null check(length(name) between 1 and 120),
 description text not null default '',
 created_at timestamptz not null default now()
);
create table public.prompt_chain_steps (
 id bigint generated by default as identity primary key,
 prompt_chain_id bigint not null references public.prompt_chains(id) on delete cascade,
 model_id bigint not null references public.llm_models(id) on delete restrict,
 name text not null check(length(name) between 1 and 120),
 prompt text not null check(length(prompt) between 1 and 12000),
 position integer not null check(position >= 0),
 temperature numeric not null default 1 check(temperature between 0 and 2),
 created_at timestamptz not null default now(),
 unique(prompt_chain_id,position) deferrable initially immediate
);
create table public.prompt_chain_mix (
 id bigint generated by default as identity primary key,
 prompt_chain_id bigint not null unique references public.prompt_chains(id) on delete cascade,
 weight integer not null default 1 check(weight between 0 and 10000),
 enabled boolean not null default true,
 created_at timestamptz not null default now()
);
create function public.initialize_chain_mix() returns trigger language plpgsql security definer set search_path='' as $$
begin insert into public.prompt_chain_mix(prompt_chain_id) values(new.id); return new; end; $$;
create trigger initialize_chain_mix after insert on public.prompt_chains for each row execute function public.initialize_chain_mix();
create table public.terms (
 id bigint generated by default as identity primary key,
 term text not null unique check(length(term) between 1 and 200),
 definition text not null check(length(definition) between 1 and 5000),
 created_at timestamptz not null default now()
);
create table public.ai_generation_examples (
 id bigint generated by default as identity primary key,
 prompt text not null check(length(prompt) between 1 and 12000),
 response text not null check(length(response) between 1 and 12000),
 notes text not null default '',
 created_at timestamptz not null default now()
);
create table public.allowed_signup_domains (
 id bigint generated by default as identity primary key,
 domain text not null unique check(domain = lower(domain) and domain ~ '^[a-z0-9][a-z0-9.-]*\.[a-z]{2,}$'),
 created_at timestamptz not null default now()
);
create table public.whitelisted_emails (
 id bigint generated by default as identity primary key,
 email text not null unique check(email = lower(email) and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
 created_at timestamptz not null default now()
);
create table public.generation_requests (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 prompt_chain_id bigint references public.prompt_chains(id) on delete set null,
 input text not null,
 status text not null default 'running' check(status in ('running','succeeded','failed')),
 error text,
 created_at timestamptz not null default now(),
 completed_at timestamptz
);
create table public.llm_responses (
 id bigint generated by default as identity primary key,
 request_id uuid not null references public.generation_requests(id) on delete cascade,
 step_id bigint references public.prompt_chain_steps(id) on delete set null,
 model text not null,
 prompt text not null,
 response text not null,
 duration_ms integer check(duration_ms >= 0),
 created_at timestamptz not null default now()
);
create table public.chain_media (
 id bigint generated by default as identity primary key,
 request_id uuid not null unique references public.generation_requests(id) on delete cascade,
 prompt_chain_id bigint references public.prompt_chains(id) on delete set null,
 content text not null,
 created_at timestamptz not null default now()
);
create table public.images (
 id bigint generated by default as identity primary key,
 storage_path text not null unique,
 alt text not null default '',
 created_at timestamptz not null default now()
);
alter table public.llm_providers enable row level security;
alter table public.llm_providers force row level security;
revoke all on public.llm_providers from anon, authenticated;
grant select,insert,update,delete on public.llm_providers to authenticated;
create policy "Superadmins manage llm_providers" on public.llm_providers for all to authenticated using ((select public.is_superadmin())) with check ((select public.is_superadmin()));
