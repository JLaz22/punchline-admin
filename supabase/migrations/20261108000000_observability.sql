grant usage, select on all sequences in schema public to authenticated;
-- Public-app telemetry is scoped to the signed-in author; other users cannot read it.
create policy "Authors insert requests" on public.generation_requests for insert to authenticated with check(user_id=auth.uid() and prompt_chain_id is null);
create policy "Authors read requests" on public.generation_requests for select to authenticated using(user_id=auth.uid());
create policy "Authors finish requests" on public.generation_requests for update to authenticated using(user_id=auth.uid() and prompt_chain_id is null) with check(user_id=auth.uid() and prompt_chain_id is null);
create policy "Authors record responses" on public.llm_responses for insert to authenticated with check(step_id is null and exists(select 1 from public.generation_requests r where r.id=request_id and r.user_id=auth.uid() and r.prompt_chain_id is null));
